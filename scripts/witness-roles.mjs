/* F7 witness: drone bays, laser siphon, wing escorts, mender, role label.
 * node scripts/witness-roles.mjs [chromium|firefox] */
import { mkdirSync } from 'node:fs';
const { chromium, firefox } = await import(process.env.PLAYWRIGHT_PATH || 'playwright');
const browserName = process.argv[2] || 'chromium';
const out = `shots/roles/${browserName}`; mkdirSync(out, { recursive: true });
const b = await ({ chromium, firefox })[browserName].launch(process.env.PW_EXECUTABLE ? { executablePath: process.env.PW_EXECUTABLE } : {});
const page = await b.newPage({ viewport: { width: 1366, height: 768 } });
const errors = []; page.on('pageerror', e => errors.push(String(e)));
let pass = 0, fail = 0;
const check = (n, ok, v) => { console.log(`${ok ? 'PASS' : 'FAIL'} ${n}${ok ? '' : ': ' + JSON.stringify(v)}`); ok ? pass++ : fail++; };
await page.goto(process.env.GAME_URL || 'http://127.0.0.1:8811/'); await page.evaluate(() => localStorage.clear()); await page.reload();
await page.waitForFunction(() => window.roles && window.hubs && window.menu);
const r = await page.evaluate(() => {
  document.getElementById('title-callsign').value = 'ODD'; garage.launch(false); garage.closeMission();
  const step = n => { for (let i = 0; i < n; i++) { engine.paused = false; engine.mapOpen = false; engine.update(1000 / 60); } };
  const o = {};
  o.catalogue = ['bay', 'siphon', 'wing', 'mender'].every(t => fleet.equips().some(p => p.type === t));
  const ship = (extra) => engine.applyDesign({ id: 'odd', color: '#5ef2e0', primaryWeapon: 'spitter', secAbility: 'shield',
    nodes: [{ dx: 0, dy: 0, radius: 20, type: 'core' }, { dx: 26, dy: 0, radius: 10, type: 'cannon' }, ...extra] });
  engine.player.iFrames = 99999;
  ship([{ dx: -10, dy: 30, radius: 14, type: 'bay' }, { dx: -10, dy: -30, radius: 14, type: 'bay' }]);
  o.carrier = roles.label();
  step(75);
  o.drones = engine.drones.filter(d => d.fromBay).length;
  engine.player.nodes.find(n => n.type === 'bay').lost = true; step(2);
  o.dronesAfterLoss = engine.drones.filter(d => d.fromBay).length;
  ship([{ dx: 20, dy: 22, radius: 12, type: 'siphon' }, { dx: 20, dy: -22, radius: 12, type: 'siphon' }]);
  o.siphon = roles.label();
  engine.enemies.length = 0;
  const e = new EnemyOrganism(engine.player.x + 170, engine.player.y, { tier: 6, archetype: 'mote' }); e.shield = 0; engine.enemies.push(e);
  engine.player.hp = engine.player.maxHp - 60; const hp0 = engine.player.hp, ehp0 = e.hp;
  engine.readInput = () => (engine.input = { ax: 0, ay: 0, aimX: e.x, aimY: e.y, fire: true, ability: false });
  step(60);
  o.siphonDamage = Math.round(ehp0 - e.hp); o.siphonHeal = Math.round(engine.player.hp - hp0); o.beams = roles.beams.length;
  engine.enemies.length = 0;
  ship([{ dx: -20, dy: 26, radius: 16, type: 'wing' }]);
  o.wing = roles.label();
  step(40);
  o.escorts = roles.escorts.length;
  const e2 = new EnemyOrganism(engine.player.x + 300, engine.player.y + 100, { tier: 1, archetype: 'mote' }); e2._aggro = false; engine.enemies.push(e2);
  const shots0 = engine.projectiles.filter(p => p.isPlayer).length;
  engine.readInput = () => (engine.input = { ax: 0, ay: 0, aimX: engine.player.x + 100, aimY: engine.player.y, fire: false, ability: false });
  step(60);
  o.escortFired = engine.projectiles.filter(p => p.isPlayer).length > shots0 || !engine.enemies.includes(e2) || e2.hp < e2.maxHp;
  engine.enemies.length = 0;
  ship([{ dx: -10, dy: 26, radius: 12, type: 'mender' }, { dx: -10, dy: -26, radius: 12, type: 'mender' }, { dx: 30, dy: 0, radius: 10, type: 'pod' }]);
  o.mender = roles.label();
  engine.player.nodes.find(n => n.type === 'pod').lost = true;
  step(roles.CFG.menderEvery + 2);
  o.regrown = !engine.player.nodes.find(n => n.type === 'pod').lost;
  ship([]); o.gunship = roles.label();
  return o;
});
check('the four oddities are in the parts catalogue', r.catalogue, r);
check('2 drone bays = CARRIER with 2 drones; losing a bay loses its drone', r.carrier === 'CARRIER' && r.drones === 2 && r.dronesAfterLoss === 1, r);
check('2 siphons = SIPHON; the beam drains a hull and heals you', r.siphon === 'SIPHON' && r.siphonDamage > 20 && r.siphonHeal > 5 && r.beams === 2, r);
check('a wing dock = WING LEADER; its escort launches and fights', r.wing === 'WING LEADER' && r.escorts === 1 && r.escortFired, r);
check('2 menders = MENDER; the pulse regrows a lost part', r.mender === 'MENDER' && r.regrown, r);
check('no oddities = GUNSHIP', r.gunship === 'GUNSHIP', r);
await page.evaluate(() => { engine.paused = false; }); await page.keyboard.press('y'); await page.waitForTimeout(600);
await page.evaluate(() => document.querySelector('[data-category="odd"]').click()); await page.waitForTimeout(200);
await page.screenshot({ path: `${out}/shipyard-oddities.png` });
const y = await page.evaluate(() => ({ cards: document.querySelectorAll('#sy-parts .part-card').length, chip: (document.getElementById('role-chip') || {}).textContent || '' }));
check('the Shipyard has an Oddities tab with 7 parts and a ROLE chip', y.cards === 7 && /ROLE/.test(y.chip), y);
check('no page errors', errors.length === 0, errors);
console.log(`RESULT ${pass} passed / ${fail} failed`);
await b.close(); process.exit(fail ? 1 : 0);
