#!/usr/bin/env python3
"""Build js/canon-lore.js from docs/canon/COMPLETE_PANTHEON_LORE_15_CIVILISATIONS.md (Mac's authored codex).

    python3 scripts/build-lore.py

The text is carried over as written: each civilisation's sections ("Galactic Origin", "Territory / Home Systems", ...)
become a list of paragraphs, keyed by the canon id in js/canon.js (matched on canon order). Markdown emphasis is
dropped; a quote line (">") is kept as a quote. Regenerate it when the canon doc changes; never hand-edit the output.
"""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'docs/canon/COMPLETE_PANTHEON_LORE_15_CIVILISATIONS.md'
OUT = ROOT / 'js/canon-lore.js'


def canon_ids():
    text = (ROOT / 'js/canon.js').read_text()
    data = json.loads(text[text.index('{'):text.rindex('}') + 1])
    return {c['order']: c['id'] for c in data['civilisations']}


def plain(line):
    line = re.sub(r'\*\*(.+?)\*\*', r'\1', line)
    line = re.sub(r'(?<!\*)\*(?!\s)(.+?)(?<!\s)\*(?!\*)', r'\1', line)
    return re.sub(r'`(.+?)`', r'\1', line).strip()


def main():
    ids, civs, civ, section, para = canon_ids(), {}, None, None, []

    def flush():
        nonlocal para
        if section is not None and para:
            # a long line is wrapped prose (joined with a space); a short one is a written line break (kept)
            text = ''.join(l + (' ' if len(l) >= 80 else '\n') for l in para[1:]).strip()
            section['p'].append({'q': True, 't': text} if para[0] == '>' else {'t': text})
        para = []

    for raw in SRC.read_text().splitlines():
        line = raw.rstrip()
        m = re.match(r'^## (\d+)\. (.+?) — (.+)$', line)
        if m:
            flush()
            cid = ids[int(m.group(1))]
            civ = civs[cid] = {'name': m.group(2), 'epithet': m.group(3), 'sections': []}
            section = {'title': 'Overview', 'p': []}
            civ['sections'].append(section)
            continue
        if civ is None:
            continue
        m = re.match(r'^### (.+)$', line)
        if m:
            flush()
            section = {'title': plain(m.group(1)), 'p': []}
            civ['sections'].append(section)
            continue
        if not line.strip():
            flush()
            continue
        quote = line.startswith('>')
        text = plain(line.lstrip('> ').strip())
        if para and (para[0] == '>') != quote:
            flush()
        if not para:
            para = ['>' if quote else '']
        para.append(text)
    flush()
    for c in civs.values():
        c['sections'] = [s for s in c['sections'] if s['p']]
    head = ('/* CANON LORE. Generated by scripts/build-lore.py from docs/canon/COMPLETE_PANTHEON_LORE_15_CIVILISATIONS.md\n'
            '   (Mac\'s authored Pantheon codex, Forge 0.77.11). The text is carried over as written. Do not hand-edit:\n'
            '   change the canon doc and regenerate. Read by js/lore-codex.js. */\n')
    OUT.write_text(head + 'window.canonLore = ' + json.dumps(civs, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print(f'{len(civs)} civilisations, {sum(len(c["sections"]) for c in civs.values())} sections -> {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
