/* F1 witness: pause + title doors + settings + Continue-where-you-left-off.
 * node scripts/witness-menu.mjs [chromium|firefox]   (PW_EXECUTABLE overrides the browser binary)
 * Screenshots: shots/menu/<browser>/ */
import { mkdirSync, writeFileSync } from 'node:fs';
const { chromium, firefox } = await import(process.env.PLAYWRIGHT_PATH || 'playwright');
const browserName = process.argv[2] || 'chromium';
const URL = process.env.GAME_URL || 'http://127.0.0.1:8811/';
const out = `shots/menu/${browserName}`; mkdirSync(out, { recursive: true });
const b = await ({ chromium, firefox })[browserName].launch(process.env.PW_EXECUTABLE ? { executablePath: process.env.PW_EXECUTABLE } : {});
const page = await b.newPage({ viewport: { width: 1366, height: 768 } });
const errs = []; page.on('pageerror', e => errs.push(String(e))); page.on('response', r => { if (r.status() >= 400) errs.push(r.status() + ' ' + r.url()); });
const R = {};
await page.goto(URL); await page.evaluate(() => localStorage.clear()); await page.reload();
await page.waitForTimeout(1200);
await page.screenshot({ path: out + '/title-fresh.png' });
R.freshDoors = await page.evaluate(() => ({ cont: getComputedStyle(document.getElementById('btn-title-continue')).display, newg: !!document.getElementById('btn-menu-new').offsetParent }));
await page.click('#btn-menu-new'); await page.waitForTimeout(200);
R.newVisible = await page.evaluate(() => !!document.getElementById('title-callsign').offsetParent);
await page.screenshot({ path: out + '/newgame.png' });
await page.keyboard.press('Escape'); await page.waitForTimeout(200);
R.backToDoors = await page.evaluate(() => !!document.getElementById('btn-menu-new').offsetParent);
await page.click('#btn-menu-new'); await page.fill('#title-callsign', 'MACTEST'); await page.click('#btn-title-quick');
await page.waitForTimeout(400);
await page.evaluate(() => garage.closeMission && garage.closeMission());
R.flying = await page.evaluate(() => !engine.paused);
await page.keyboard.down('KeyD'); await page.waitForTimeout(1500); await page.keyboard.up('KeyD');
await page.keyboard.press('Escape'); await page.waitForTimeout(300);
R.escPauses = await page.evaluate(() => engine.paused && menu.isPaused());
await page.screenshot({ path: out + '/pause.png' });
const t0 = await page.evaluate(() => engine._simulationTicks); await page.waitForTimeout(500);
R.frozen = await page.evaluate(t => engine._simulationTicks === t, t0);
await page.keyboard.press('Escape'); await page.waitForTimeout(200);
R.escResumes = await page.evaluate(() => !engine.paused && !menu.isPaused());
await page.keyboard.press('KeyP'); await page.waitForTimeout(200);
R.pPauses = await page.evaluate(() => engine.paused && menu.isPaused());
await page.keyboard.press('KeyM'); await page.waitForTimeout(400);
R.mapOverPause = await page.evaluate(() => engine.mapOpen && !menu.isPaused());
await page.keyboard.press('Escape'); await page.waitForTimeout(400);
R.mapClosesBackToPause = await page.evaluate(() => !engine.mapOpen && menu.isPaused() && engine.paused);
await page.click('#btn-pause-settings'); await page.waitForTimeout(200);
await page.screenshot({ path: out + '/settings.png' });
await page.evaluate(() => { const i = document.getElementById('set-music'); i.value = 30; i.dispatchEvent(new Event('input')); const c = document.getElementById('set-reducedMotion'); c.checked = true; c.dispatchEvent(new Event('change')); });
await page.keyboard.press('Escape'); await page.waitForTimeout(400);
R.settingsBackToPause = await page.evaluate(() => menu.isPaused());
R.reduced = await page.evaluate(() => JUICE.shake === 0 && JUICE.hitStopMs === 0);
await page.click('#btn-pause-shipyard'); await page.waitForTimeout(500);
R.yardOpen = await page.evaluate(() => shipyard.open && !menu.isPaused());
await page.keyboard.press('Escape'); await page.waitForTimeout(400);
R.yardBackToPause = await page.evaluate(() => !shipyard.open && menu.isPaused());
const pos = await page.evaluate(() => ({ x: engine.player.x, gx: worldMap.currentGridX }));
await page.click('#btn-pause-quit'); await page.waitForTimeout(300);
await page.screenshot({ path: out + '/title-returning.png' });
R.quitTitle = await page.evaluate(() => getComputedStyle(document.getElementById('btn-title-continue')).display !== 'none');
await page.reload(); await page.waitForTimeout(1200);
R.settingsPersist = await page.evaluate(() => saveState.doc.settings.music === 0.3 && saveState.doc.settings.reducedMotion === true);
await page.click('#btn-title-continue'); await page.waitForTimeout(400);
R.continueWhere = await page.evaluate(p => ({ saved: p, now: { x: Math.round(engine.player.x), gx: worldMap.currentGridX }, paused: engine.paused }), pos);
await page.click('#btn-open-menu'); await page.waitForTimeout(200);
R.menuBtn = await page.evaluate(() => menu.isPaused());
await page.click('#btn-pause-howto'); await page.waitForTimeout(200);
await page.screenshot({ path: out + '/howto.png' });
await page.setViewportSize({ width: 412, height: 860 });
await page.keyboard.press('Escape'); await page.waitForTimeout(300);
await page.screenshot({ path: out + '/pause-phone.png' });
await page.click('#btn-pause-quit'); await page.waitForTimeout(300);
await page.screenshot({ path: out + '/title-phone.png' });
R.errors = errs;
let pass = 0, fail = 0;
const expect = { freshDoors: v => v.cont === 'none' && v.newg, continueWhere: v => v.now.gx === v.saved.gx && Math.abs(v.now.x - v.saved.x) < 2 && !v.paused, errors: v => v.length === 0 };
for (const [k, v] of Object.entries(R)) {
  const ok = expect[k] ? expect[k](v) : v === true;
  console.log(`${ok ? 'PASS' : 'FAIL'} ${k}${ok ? '' : ': ' + JSON.stringify(v)}`); ok ? pass++ : fail++;
}
writeFileSync(`${out}/report.json`, JSON.stringify(R, null, 1));
console.log(`RESULT ${pass} passed / ${fail} failed`);
await b.close();
process.exit(fail ? 1 : 0);
