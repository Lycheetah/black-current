"""Regenerate the blueprint and model registries from the files on disk.
    python3 tools/register-ships.py
Every src/data/blueprints/<id>.json and src/data/models/<name>.glb is listed (picker order: by class, then id)."""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BP = os.path.join(ROOT, 'src/data/blueprints')
MD = os.path.join(ROOT, 'src/data/models')
ORDER = ['starter', 'frigate', 'destroyer', 'cruiser', 'battleship']
camel = lambda s: re.sub(r'_(\w)', lambda m: m.group(1).upper(), s)

bps = []
for f in sorted(os.listdir(BP)):
    if f.endswith('.json'):
        d = json.load(open(os.path.join(BP, f)))
        bps.append((ORDER.index(d['class']) if d['class'] in ORDER else 9, d['id'], f))
bps.sort()
lines = ['// Authored blueprint overrides. A blueprint here replaces the generated one for the hull with the same id.',
         '// Generated by tools/register-ships.py from the files in this folder (picker order: class, then id).']
lines += [f"import {camel(i)} from './{f}' with {{ type: 'json' }};" for _, i, f in bps]
lines += ['', 'export const AUTHORED_BLUEPRINTS = [' + ', '.join(camel(i) for _, i, _ in bps) + '];', '']
open(os.path.join(BP, 'index.js'), 'w').write('\n'.join(lines))

glbs = sorted(f for f in os.listdir(MD) if f.endswith('.glb'))
lines = ['// Ship models (and the turret set). Generated by tools/register-ships.py from the .glb files here.',
         '// Each becomes a separate file next to the page (or a data URL in the single-file build).']
lines += [f"import {camel(f[:-4])} from './{f}';" for f in glbs]
lines += ['', 'export const MODEL_FILES = {'] + [f"  '{f}': {camel(f[:-4])}," for f in glbs] + ['};', '']
open(os.path.join(MD, 'index.js'), 'w').write('\n'.join(lines))
print(len(bps), 'blueprints ·', len(glbs), 'models')
